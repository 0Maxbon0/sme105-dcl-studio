import test from 'node:test';
import assert from 'node:assert/strict';
import { throttlePercent, dashboardReading } from '../js/throttle-display.js';
import { rowsToCsv } from '../js/pids.js';
import { chartPoints } from '../js/chart-series.js';
test('normal throttle card uses the fixed 179–970 range with clamping and no profile', () => {
  assert.equal(throttlePercent(179),0);
  assert.equal(throttlePercent(500),41);
  assert.equal(throttlePercent(867),87);
  assert.equal(throttlePercent(574.5),50);
  assert.equal(throttlePercent(970),100);
  for(const raw of [0,103,170,178]) assert.equal(throttlePercent(raw),0);
  for(const raw of [971,1013]) assert.equal(throttlePercent(raw),100);
  for(const raw of [null,undefined,NaN,Infinity]) assert.equal(throttlePercent(raw),null);
  assert.deepEqual(dashboardReading('THROTTLE_PERCENT',179),{value:0,unit:'%'});
  const rows=[{t:0,name:'ITP',raw:179,value:179},{t:1,name:'ITP',raw:970,value:970}];
  assert.deepEqual(chartPoints(rows,'THROTTLE_PERCENT','full').map(p=>p.value),[0,100]);
  assert.deepEqual(dashboardReading('ITP',179),{value:179,unit:'counts'});
  assert.deepEqual(chartPoints(rows,'ITP','full').map(p=>p.value),[179,970]);
  const csv=rowsToCsv(rows);assert.match(csv,/0,ITP,179,179,A\/D,179,counts/);assert.match(csv,/1,ITP,970,970,A\/D,970,counts/);
  assert.deepEqual(rows.map(s=>s.raw),[179,970]);
});
